export const THORN_BUSH = {
  /** 刺：比以前細、短、多、淡（以前 4 根粗的米白色長刺，遠看像插了牙籤） */
  thorns: 6, thornW: 1.5, thornLen: 0.24, thornA: 0.5, thornColor: 0xc8a88a,
  /** 漿果：以前 25% 的叢有一顆亮紅（0xff4a5a）的；現在少、小、暗 */
  berryRate: 0.1, berryR: 0.08, berryColor: 0x8a3044,
} as const;

export interface Lobe { x: number; y: number; r: number; hi: boolean }

/**
 * 一叢裡的葉簇（座標與半徑都是叢半徑的倍數；h1～h3 是這一格的雜湊 0～1）。
 * 三團：兩團亮一階的在上半（光從左上來）、一團暗的在右下；最多凸出叢的大圓一成多：輪廓有一點起伏，牆看起來的邊界幾乎不變。
 */
export function thornLobes(h1: number, h2: number, h3: number): Lobe[] {
  return [
    { x: -0.3 + (h1 - 0.5) * 0.2, y: -0.28 + (h2 - 0.5) * 0.16, r: 0.5 + h3 * 0.08, hi: true },
    { x: 0.3 + (h2 - 0.5) * 0.2, y: -0.12 + (h3 - 0.5) * 0.16, r: 0.4 + h1 * 0.08, hi: true },
    { x: 0.05 + (h3 - 0.5) * 0.2, y: 0.34 + (h1 - 0.5) * 0.12, r: 0.42 + h2 * 0.08, hi: false },
  ];
}
